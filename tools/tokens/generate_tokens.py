#!/usr/bin/env python3
"""Lumen token generator.

Reads ``kit/tokens/lumen.tokens.json`` (the single source of truth for the
Lumen design language) and generates:

* ``kit/Tokens.qml``                  – a typed QML singleton consumed by QTOS.Kit
* ``platform/common/lumentokens.h``  – C++ constants for the QStyle / platform theme
* ``docs/design/tokens.md``           – the human-readable token reference

Usage::

    python tools/tokens/generate_tokens.py           # regenerate outputs
    python tools/tokens/generate_tokens.py --check   # CI: fail if outputs are stale

The OKLCH -> sRGB conversion here mirrors ``kit/src/oklch.cpp`` so the docs show
exactly the colors the runtime produces.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TOKENS_JSON = REPO / "kit" / "tokens" / "lumen.tokens.json"
TOKENS_QML = REPO / "kit" / "Tokens.qml"
TOKENS_MD = REPO / "docs" / "design" / "tokens.md"
TOKENS_CPP = REPO / "platform" / "common" / "lumentokens.h"

HEADER = (
    "// Generated by tools/tokens/generate_tokens.py from kit/tokens/lumen.tokens.json.\n"
    "// DO NOT EDIT: change the JSON source and re-run the generator.\n"
)


# ── Color math (OKLCH → OKLab → linear sRGB → sRGB) ──────────────────────────

def oklch_to_linear_srgb(l: float, c: float, h_deg: float) -> tuple[float, float, float]:
    h = math.radians(h_deg)
    a = c * math.cos(h)
    b = c * math.sin(h)
    l_ = l + 0.3963377774 * a + 0.2158037573 * b
    m_ = l - 0.1055613458 * a - 0.0638541728 * b
    s_ = l - 0.0894841775 * a - 1.2914855480 * b
    l3, m3, s3 = l_ ** 3, m_ ** 3, s_ ** 3
    return (
        +4.0767416621 * l3 - 3.3077115913 * m3 + 0.2309699292 * s3,
        -1.2684380046 * l3 + 2.6097574011 * m3 - 0.3413193965 * s3,
        -0.0041960863 * l3 - 0.7034186147 * m3 + 1.7076147010 * s3,
    )


def _in_gamut(rgb: tuple[float, float, float], eps: float = 1e-5) -> bool:
    return all(-eps <= ch <= 1.0 + eps for ch in rgb)


def oklch_to_srgb(l: float, c: float, h: float) -> tuple[float, float, float]:
    """Converts OKLCH to gamma-encoded sRGB, reducing chroma to stay in gamut."""
    rgb = oklch_to_linear_srgb(l, c, h)
    if not _in_gamut(rgb):
        lo, hi = 0.0, c
        for _ in range(24):
            mid = (lo + hi) / 2
            if _in_gamut(oklch_to_linear_srgb(l, mid, h)):
                lo = mid
            else:
                hi = mid
        rgb = oklch_to_linear_srgb(l, lo, h)

    def encode(x: float) -> float:
        x = min(max(x, 0.0), 1.0)
        return 12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055

    return tuple(encode(ch) for ch in rgb)  # type: ignore[return-value]


def to_hex(l: float, c: float, h: float, alpha: float) -> str:
    r, g, b = oklch_to_srgb(l, c, h)
    hexrgb = "#{:02x}{:02x}{:02x}".format(*(round(ch * 255) for ch in (r, g, b)))
    return hexrgb if alpha >= 0.999 else f"{hexrgb} @ {alpha:.0%}"


# ── QML emission ──────────────────────────────────────────────────────────────

def qml_number(value: float | int) -> str:
    if isinstance(value, int) or float(value).is_integer():
        return str(int(value))
    return repr(round(float(value), 6))


def qml_list(values: list[float]) -> str:
    return "[" + ", ".join(qml_number(v) for v in values) + "]"


def emit_qml(tokens: dict) -> str:
    color = tokens["color"]
    roles = color["roles"]
    spdx = "// SPDX-License-Identifier: LicenseRef-QTOS-Proprietary\n"
    out: list[str] = [HEADER + spdx, "pragma Singleton", "import QtQml", "", "QtObject {"]

    def line(text: str = "", indent: int = 1) -> None:
        out.append(("    " * indent + text) if text else "")

    line("// ── Typed token groups ─────────────────────────────────────────")
    line("component ColorRoles: QtObject {")
    for name, role in roles.items():
        follow = "true" if role.get("followAccent") else "false"
        line(
            f"readonly property var {name}: ({{ \"light\": {qml_list(role['light'])}, "
            f"\"dark\": {qml_list(role['dark'])}, \"followAccent\": {follow} }})",
            2,
        )
    line("}")
    line()

    for comp, key in (("RadiusTokens", "radius"), ("SpacingTokens", "spacing")):
        line(f"component {comp}: QtObject {{")
        for name, value in tokens[key].items():
            line(f"readonly property real {name}: {qml_number(value)}", 2)
        line("}")
        line()

    line("component TypeStyle: QtObject {")
    line("property real size", 2)
    line("property int weight", 2)
    line("property real tracking", 2)
    line("property real opsz", 2)
    line("}")
    line()
    line("component TypographyTokens: QtObject {")
    for name, style in tokens["type"].items():
        line(
            f"readonly property TypeStyle {name}: TypeStyle {{ size: {qml_number(style['size'])}; "
            f"weight: {style['weight']}; tracking: {qml_number(style['tracking'])}; "
            f"opsz: {qml_number(style['opsz'])} }}",
            2,
        )
    line("}")
    line()

    motion = tokens["motion"]
    line("component MotionTokens: QtObject {")
    for name, value in motion.items():
        if isinstance(value, dict):
            line(
                f"readonly property var {name}: ({{ \"response\": {qml_number(value['response'])}, "
                f"\"damping\": {qml_number(value['damping'])} }})",
                2,
            )
        else:
            line(f"readonly property int {name}: {qml_number(value)}", 2)
    line("}")
    line()

    line("component MaterialTokens: QtObject {")
    for name, value in tokens["material"].items():
        line(f"readonly property real {name}: {qml_number(value)}", 2)
    line("}")
    line()

    line("// ── Values ─────────────────────────────────────────────────────")
    line(f"readonly property string name: \"{tokens['meta']['name']}\"")
    line(f"readonly property string version: \"{tokens['meta']['version']}\"")
    line(f"readonly property real accentDefaultHue: {qml_number(color['accentDefaultHue'])}")
    line(f"readonly property list<real> accentPresets: {qml_list(color['accentPresets'])}")
    line("readonly property ColorRoles color: ColorRoles {}")
    line("readonly property RadiusTokens radius: RadiusTokens {}")
    line("readonly property SpacingTokens spacing: SpacingTokens {}")
    line("readonly property TypographyTokens typography: TypographyTokens {}")
    line("readonly property MotionTokens motion: MotionTokens {}")
    line("readonly property MaterialTokens material: MaterialTokens {}")
    elevations = ", ".join(
        f"({{ \"blur\": {qml_number(e['blur'])}, \"offsetY\": {qml_number(e['offsetY'])}, "
        f"\"opacity\": {qml_number(e['opacity'])} }})"
        for e in tokens["elevation"]
    )
    line(f"readonly property var elevation: [{elevations}]")
    out.append("}")
    return "\n".join(out) + "\n"


# ── C++ emission ─────────────────────────────────────────────────────────────

def emit_cpp(tokens: dict) -> str:
    color = tokens["color"]
    lines = [
        HEADER.rstrip("\n"),
        "// SPDX-License-Identifier: LicenseRef-QTOS-Proprietary",
        "#pragma once",
        "",
        "// Lumen tokens for C++ consumers (Qt Widgets style, QPA platform theme).",
        "// Colors are OKLCH {L, C, H, A}; hue is an offset from the accent hue when",
        "// followAccent is true.",
        "namespace qtos::lumen {",
        "",
        "struct Oklch { double l, c, h, a; };",
        "struct ColorRole { Oklch light; Oklch dark; bool followAccent; };",
        "",
        f"inline constexpr double kAccentDefaultHue = {qml_number(color['accentDefaultHue'])};",
        "",
    ]
    for name, role in color["roles"].items():
        def tup(v: list[float]) -> str:
            return "{ " + ", ".join(qml_number(x) if not float(x).is_integer() else f"{int(x)}.0" for x in v) + " }"
        follow = "true" if role.get("followAccent") else "false"
        const = "k" + name[0].upper() + name[1:]
        lines.append(f"inline constexpr ColorRole {const} {{ {tup(role['light'])}, {tup(role['dark'])}, {follow} }};")
    lines.append("")
    for name, value in tokens["radius"].items():
        const = "kRadius" + name[0].upper() + name[1:]
        lines.append(f"inline constexpr double {const} = {qml_number(value)};")
    lines.append("")
    for name, style in tokens["type"].items():
        const = "kType" + name[0].upper() + name[1:]
        lines.append(f"inline constexpr int {const}Size = {style['size']};")
        lines.append(f"inline constexpr int {const}Weight = {style['weight']};")
    lines += ["", "} // namespace qtos::lumen", ""]
    return "\n".join(lines)


# ── Markdown emission ────────────────────────────────────────────────────────

def emit_markdown(tokens: dict) -> str:
    color = tokens["color"]
    accent = color["accentDefaultHue"]
    md: list[str] = [
        "<!-- Generated by tools/tokens/generate_tokens.py. DO NOT EDIT. -->",
        "",
        f"# Lumen token reference (v{tokens['meta']['version']})",
        "",
        "Source of truth: [`kit/tokens/lumen.tokens.json`](../../kit/tokens/lumen.tokens.json). "
        "QML access: `Tokens.<group>.<name>` (raw values) and `Theme.<role>` (resolved, animated colors).",
        "",
        f"Hex values are sRGB, gamut-mapped from OKLCH, shown with the default accent hue **{accent}°**.",
        "",
        "## Color roles",
        "",
        "| Role | Light | Dark | Follows accent |",
        "|------|-------|------|----------------|",
    ]
    for name, role in color["roles"].items():
        follow = bool(role.get("followAccent"))
        hue_shift = accent if follow else 0

        def fmt(v: list[float]) -> str:
            return f"`{to_hex(v[0], v[1], (v[2] + hue_shift) % 360, v[3])}`"

        md.append(f"| `{name}` | {fmt(role['light'])} | {fmt(role['dark'])} | {'yes' if follow else ''} |")

    md += ["", "Accent presets (hue °): " + ", ".join(str(h) for h in color["accentPresets"]), ""]

    md += ["## Radius", "", "| Token | Value |", "|-------|-------|"]
    md += [f"| `{k}` | {qml_number(v)} |" for k, v in tokens["radius"].items()]
    md += ["", "## Spacing (4 px grid)", "", "| Token | px |", "|-------|----|"]
    md += [f"| `{k}` | {qml_number(v)} |" for k, v in tokens["spacing"].items()]
    md += ["", "## Typography (Inter Variable)", "",
           "| Style | Size px | Weight (wght axis) | Tracking px | Optical size |",
           "|-------|---------|--------------------|-------------|--------------|"]
    md += [
        f"| `{k}` | {qml_number(v['size'])} | {v['weight']} | {qml_number(v['tracking'])} | {qml_number(v['opsz'])} |"
        for k, v in tokens["type"].items()
    ]
    md += ["", "## Elevation", "", "| Level | Shadow blur px | Offset Y px | Shadow opacity |",
           "|-------|----------------|-------------|----------------|"]
    md += [
        f"| {i} | {qml_number(e['blur'])} | {qml_number(e['offsetY'])} | {qml_number(e['opacity'])} |"
        for i, e in enumerate(tokens["elevation"])
    ]
    md += ["", "## Motion (springs)", "", "| Preset | Response s | Damping ratio |", "|--------|------------|---------------|"]
    for k, v in tokens["motion"].items():
        if isinstance(v, dict):
            md.append(f"| `{k}` | {qml_number(v['response'])} | {qml_number(v['damping'])} |")
    md += ["", f"Stagger between list items: {tokens['motion']['staggerMs']} ms.", ""]
    md += ["## Material", "", "| Token | Value |", "|-------|-------|"]
    md += [f"| `{k}` | {qml_number(v)} |" for k, v in tokens["material"].items()]
    md.append("")
    return "\n".join(md)


# ── Entry point ──────────────────────────────────────────────────────────────

def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify generated files are up to date")
    args = parser.parse_args(argv)

    tokens = json.loads(TOKENS_JSON.read_text(encoding="utf-8"))
    outputs = {TOKENS_QML: emit_qml(tokens), TOKENS_CPP: emit_cpp(tokens), TOKENS_MD: emit_markdown(tokens)}

    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")

    rel = [str(p.relative_to(REPO)) for p in stale]
    if args.check:
        if stale:
            print("Stale generated token files: " + ", ".join(rel), file=sys.stderr)
            print("Run: python tools/tokens/generate_tokens.py", file=sys.stderr)
            return 1
        print("Token outputs are up to date.")
        return 0

    print("Updated: " + ", ".join(rel) if rel else "Token outputs already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
